  test('backup excludes secrets and restores missing users and policy with a preview', async ({ login, page, mock }) => {
    await login({ to: '#/settings/backup' });
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download backup' }).click();
    const download = await downloaded;
    const raw = await fs.readFile((await download.path())!, 'utf8');
    const backup = JSON.parse(raw);
    expect(backup).toMatchObject({ format: 'headscale-console-backup', version: 1 });
    expect(backup.users).toHaveLength(2);
    expect(backup.nodes).toHaveLength(4);
    expect(raw).not.toContain('hskey-auth-');
    expect(raw).not.toContain('0123456789abcdefghijklmnopqrstuv');
    const upload = (text: string) => page.getByLabel('Backup file to restore').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(text) });
    await upload('not json');
    await expect(page.locator('.callout-error')).toContainText('This file is not JSON');
    await upload(raw);
    await expect(page.locator('.callout-success')).toContainText('Nothing to restore');
    backup.users.push({ id: '99', name: 'restored', displayName: 'Restored User', email: 'restored@example.com' });
    backup.policy = '{"acls": []}';
    await upload(JSON.stringify(backup));
    await expect(page.locator('.settings-panel')).toContainText('Create 1 missing user: restored');
    await expect(page.locator('.diff-add')).toContainText('{"acls": []}');
    const restore = page.locator('#main').getByRole('button', { name: 'Restore', exact: true });
    await restore.click();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await restore.click();
    await page.getByRole('dialog').getByRole('button', { name: 'Restore', exact: true }).click();
    await expect(page.locator('.callout-success')).toContainText('1 user created and the policy replaced');
    expect((await mock('state')).users).toEqual(expect.arrayContaining([expect.objectContaining({ name: 'restored', displayName: 'Restored User' })]));
    expect((await mock('state')).policy).toBe('{"acls": []}');
    await mock('fail', { path: '^/api/v1/node$', message: 'backup unavailable' });
    await page.getByRole('button', { name: 'Download backup' }).click();
    await expect(page.locator('.toast').last()).toContainText('backup unavailable');
  });

