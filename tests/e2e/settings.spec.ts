  test('updates handle queued, running, complete, stale and failed status', async ({ login, page }) => {
    let state: Record<string, unknown> = { state: 'idle', log: '' };
    await page.route('**/host/update', async (route) => {
      if (route.request().method() === 'POST') { state = { state: 'queued', to: '0.30.1', log: '' }; await route.fulfill({ status: 202, json: { queued: '0.30.1' } }); }
      else await route.fulfill({ json: state });
    });
    await login({ to: '#/settings/updates' });
    await page.getByRole('button', { name: 'Update to 0.30.1' }).click();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Update to 0.30.1' }).click();
    await page.getByRole('dialog').locator('input').fill('0.30.1');
    await page.getByRole('dialog').getByRole('button', { name: 'Update', exact: true }).click();
    await expect(page.locator('.settings-panel')).toContainText('Update queued');
    state = { state: 'running', to: '0.30.1', message: 'installing', log: 'Installing package', at: new Date().toISOString() };
    await expect(page.locator('.settings-panel')).toContainText('Updating to 0.30.1: installing', { timeout: 7000 });
    state = { state: 'done', from: '0.29.5', to: '0.30.1', message: 'Installed successfully', log: 'all done' };
    await expect(page.locator('.toast').last()).toContainText('Headscale updated', { timeout: 7000 });
    await expect(page.locator('.settings-panel')).toContainText('Installed successfully');
    state = { state: 'stale', log: 'last log line' };
    await section(page, 'General'); await section(page, 'Updates');
    await expect(page.locator('.settings-panel')).toContainText('stopped responding');
    state = { state: 'failed', message: 'package failed', log: 'diagnostic details' };
    await section(page, 'General'); await section(page, 'Updates');
    await expect(page.locator('.settings-panel')).toContainText('package failed');
    await expect(page.locator('.settings-panel')).toContainText('diagnostic details');
    await page.unroute('**/host/update');
    await page.route('**/host/update', (route) => route.fulfill(fail('status unavailable')));
    await section(page, 'General'); await section(page, 'Updates');
    await expect(page.locator('.settings-panel')).toContainText('Could not read update status');
    await page.getByRole('button', { name: 'Update to 0.30.1' }).click();
    await page.getByRole('dialog').locator('input').fill('0.30.1');
    await page.getByRole('dialog').getByRole('button', { name: 'Update', exact: true }).click();
    await expect(page.locator('.toast').last()).toContainText('status unavailable');
    await expect(page.getByRole('button', { name: 'Update to 0.30.1' })).toBeEnabled();
  });

  test('an unavailable release feed is explained', async ({ login, page }) => {
    await login({ server: 'bare', to: '#/settings/updates' });
    await expect(page.locator('.settings-panel')).toContainText('Could not check for updates');
  });
