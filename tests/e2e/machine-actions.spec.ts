test('machine details validate names and tags, routes and expiry before saving', async ({ login, page, mock }) => {
  await login({ to: '#/machines/1' });
  await expect(page.locator('h1')).toHaveText('laptop');
  await expect(page.locator('.kv')).toContainText(['Alice Doe', '100.64.0.1', 'nodekey:']);
  await page.getByRole('button', { name: 'Edit name', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const name = dialog.getByLabel('Machine name');
  for (const [value, error] of [['', 'Name is required'], ['a'.repeat(64), '63 characters'], ['-bad', 'lowercase letters']] as const) {
    await name.fill(value);
    await dialog.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(dialog.locator('.callout-error')).toContainText(error);
  }
  await name.fill('LAPTOP');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Edit name', exact: true }).click();
  await name.fill('work-laptop');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('h1')).toHaveText('work-laptop');

  await page.locator('.card').filter({ has: page.getByRole('heading', { name: 'ACL tags', exact: true }) }).getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(dialog).toContainText('Tagging changes ownership');
  await dialog.locator('.chip-input-field').fill('bad invalid!');
  await dialog.getByRole('button', { name: 'Save tags' }).click();
  await expect(dialog).toContainText('is not a valid tag');
  await expect(dialog.locator('.chip')).toHaveCount(0);
  await dialog.locator('.chip-input-field').fill('web,WEB');
  await dialog.locator('.chip-input-field').press('Enter');
  await expect(dialog.locator('.chip')).toHaveCount(1);
  await dialog.getByRole('button', { name: 'Save tags' }).click();
  await expect(dialog).toBeHidden();
  expect((await mock('state')).nodes[0].tags).toEqual(['tag:web']);

  await page.locator('.card').filter({ has: page.getByRole('heading', { name: 'Subnets & exit node' }) }).getByRole('button', { name: 'Edit', exact: true }).click();
  const route = dialog.getByLabel('Route to approve');
  await dialog.getByRole('button', { name: 'Approve route', exact: true }).click();
  for (const [value, error] of [['bad', 'valid CIDR'], ['0.0.0.0/0', 'exit node toggle']] as const) {
    await route.fill(value);
    await route.press('Enter');
    await expect(dialog).toContainText(error);
  }
  await route.fill('172.16.0.0/16'); await route.press('Enter');
  await expect(dialog).toContainText('Not advertised');
  await route.fill('172.16.0.0/16'); await dialog.getByRole('button', { name: 'Approve route', exact: true }).click();
  await dialog.getByRole('switch', { name: 'Exit node' }).check();
  await mock('fail', { path: '/node/1/approve_routes', message: 'route write failed' });
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toContainText('route write failed');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toBeHidden();
  expect((await mock('state')).nodes[0].approvedRoutes).toEqual(['172.16.0.0/16', '0.0.0.0/0', '::/0']);

  // The switch follows the server: it flips once the change has been saved.
  await page.getByRole('switch', { name: 'Expiry', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Expiry', exact: true })).not.toBeChecked();
  await page.getByRole('switch', { name: 'Expiry', exact: true }).click();
  await dialog.getByLabel('Expires in').selectOption('custom');
  await dialog.getByLabel('Custom date', { exact: true }).fill('');
  await dialog.getByRole('button', { name: 'Save expiry' }).click();
  await expect(dialog).toContainText('Pick a date');
  await dialog.getByLabel('Custom date', { exact: true }).fill('2000-01-01');
  await dialog.getByRole('button', { name: 'Save expiry' }).click();
  await expect(dialog).toContainText('must be in the future');
  await dialog.getByLabel('Custom date', { exact: true }).fill('2099-12-31');
  await dialog.getByRole('button', { name: 'Save expiry' }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Change expiry date' }).click();
  await dialog.getByLabel('Expires in').selectOption('7');
  await dialog.getByRole('button', { name: 'Save expiry' }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Expire key now' }).click();
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  await page.getByRole('button', { name: 'Expire key now' }).click();
  await dialog.getByRole('button', { name: 'Expire key', exact: true }).click();
  await expect(page.locator('.setting-title').filter({ hasText: 'Key expired' })).toBeVisible();
  await page.getByRole('button', { name: 'Remove…', exact: true }).click();
  await dialog.getByRole('button', { name: 'Remove machine', exact: true }).click();
  await expect(page.locator('h1')).toHaveText('Machines');
  await expect(page.locator('tbody tr')).toHaveCount(3);
});

test('detail route switches, missing machines and retryable errors', async ({ login, page, mock }) => {
  await login({ to: '#/machines/2' });
  await expect(page.getByText('Routes awaiting approval', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Review routes' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click();
  const subnet = page.locator('tr', { hasText: '10.0.0.0/8' });
  await subnet.getByRole('switch').check();
  await expect(subnet).toContainText('Standby');
  await page.getByRole('switch', { name: 'Allow', exact: true }).check();
  await expect(page.getByRole('switch', { name: 'Allowed', exact: true })).toBeChecked();
  await mock('fail', { path: '/node/2/approve_routes', message: 'approval refused' });
  await page.getByRole('switch', { name: 'Allowed', exact: true }).uncheck();
  await expect(page.locator('.toast').last()).toContainText('approval refused');
  await expect(page.getByRole('switch', { name: 'Allowed', exact: true })).toBeChecked();
  await page.getByRole('switch', { name: 'Allowed', exact: true }).uncheck();
  await expect(page.getByRole('switch', { name: 'Allow', exact: true })).not.toBeChecked();
  await page.evaluate(() => { location.hash = '#/machines/missing'; });
  await expect(page.locator('.empty-title')).toHaveText('Machine not found');
  await page.getByRole('button', { name: 'Back to machines' }).click();
  await mock('fail', { path: '^/api/v1/node/3$', message: 'read failed' });
  await page.getByRole('link', { name: 'server', exact: true }).click();
  await expect(page.locator('.callout-error')).toContainText('read failed');
  await page.getByRole('button', { name: 'Try again' }).click();
  await expect(page.locator('h1')).toHaveText('server');
});

test('Add device generates commands for every OS, copies and downloads a script', async ({ login, page, mock }) => {
  await login({ to: '#/machines' });
  await page.getByRole('button', { name: 'Add device', exact: true }).click();
  const d = page.getByRole('dialog');
  await d.getByLabel('Owner', { exact: true }).selectOption('');
  await d.getByRole('button', { name: 'Generate install command' }).click();
  await expect(d).toContainText('must have at least one tag');
  await d.locator('.chip-input-field').fill('web');
  await d.getByLabel('Reusable').check();
  await d.getByLabel('Ephemeral').check();
  await d.getByLabel('Key valid for').selectOption('168');
  await mock('fail', { path: '^/api/v1/preauthkey$', method: 'POST', message: 'key creation failed' });
  await d.getByRole('button', { name: 'Generate install command' }).click();
  await expect(d).toContainText('key creation failed');
  await d.getByRole('button', { name: 'Generate install command' }).click();
  await expect(d).toContainText('Auth key created');
  const state = await mock('state');
  expect(state.keys.at(-1)).toMatchObject({ user: null, reusable: true, ephemeral: true, aclTags: ['tag:web'] });
  await d.getByRole('tab', { name: 'Linux', exact: true }).click();
  const command = d.locator('.codeblock pre').last();
  await expect(command).toContainText('tailscale.com/install.sh');
  await d.getByText('Command options', { exact: true }).click();
  for (const label of ['Single line', 'Advertise exit node', 'Tailscale SSH', 'Reset settings', 'Shields up', 'Allow LAN with exit node', 'Force re-authentication', 'Show QR code']) await d.getByLabel(label, { exact: true }).check();
  await d.getByLabel('Accept routes', { exact: true }).uncheck();
  await d.getByLabel('Accept DNS', { exact: true }).uncheck();
  await d.getByLabel('Hostname', { exact: true }).fill('My-Host!');
  await d.getByLabel('Advertise routes', { exact: true }).fill('192.168.2.0/24, bad');
  await d.getByLabel('Use exit node', { exact: true }).fill('100.64.0.2;bad');
  await d.getByLabel('Operator (Linux user)', { exact: true }).fill('alice!');
  await expect(command).toContainText('--hostname=my-host');
  await expect(command).toContainText('--advertise-routes=192.168.2.0/24');
  expect(await command.textContent()).not.toContain('\n');
  const downloaded = page.waitForEvent('download');
  await d.getByRole('button', { name: 'Download as script' }).click();
  const script = await fs.readFile(await (await downloaded).path(), 'utf8');
  expect(script).toContain('#!/bin/sh');
  await d.getByRole('tab', { name: 'macOS', exact: true }).click();
  await expect(command).toContainText('Tailscale-latest-macos.pkg');
  await d.getByRole('tab', { name: 'Windows', exact: true }).click();
  await expect(command).toContainText('winget');
  await expect(command).toContainText('; ');
  await d.getByRole('tab', { name: 'Docker', exact: true }).click();
  await expect(command).toContainText('docker run');
  await d.getByRole('tab', { name: 'Docker Compose', exact: true }).click();
  await expect(command).toContainText('services:');
  await d.getByRole('tab', { name: 'Linux', exact: true }).click();
  await d.getByLabel('Install Tailscale', { exact: true }).uncheck();
  await d.getByLabel('Show status afterwards', { exact: true }).uncheck();
  await expect(command).not.toContainText('tailscale status');
  await d.locator('.codeblock').last().getByRole('button').click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('tailscale up');
});

test('Add device registration validates input and accepts current and legacy IDs', async ({ login, page, mock }) => {
  await login({ to: '#/machines' });
  const open = async () => {
    await page.getByRole('button', { name: 'Add device', exact: true }).click();
    await page.getByRole('tab', { name: 'Register with auth ID' }).click();
  };
  await open();
  const d = page.getByRole('dialog');
  await d.getByRole('button', { name: 'Register device' }).click();
  await expect(d).toContainText('Paste the registration URL');
  await d.getByLabel('Registration URL or auth ID').fill('hskey-authreq-PENDING1');
  await mock('fail', { path: '/auth/register', message: 'approval failed' });
  await d.getByRole('button', { name: 'Register device' }).click();
  await expect(d).toContainText('approval failed');
  await d.getByLabel('Registration URL or auth ID').fill('https://example.test/register/hskey-authreq-PENDING1');
  await d.getByRole('button', { name: 'Register device' }).click();
  await expect(d).toBeHidden();
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await open();
  await d.getByLabel('Registration URL or auth ID').fill('https://example.test/register/legacy-key');
  await d.getByRole('button', { name: 'Register device' }).click();
  await expect(d).toBeHidden();
  await expect(page.locator('tbody tr')).toHaveCount(6);
  await mock('set', { users: [] });
  await page.getByRole('button', { name: 'Refresh' }).click();
  await expect.poll(async () => page.locator('tbody tr').count()).toBe(6);
  await open();
  await d.getByLabel('Registration URL or auth ID').fill('key=legacy-key');
  await d.getByRole('button', { name: 'Register device' }).click();
  await expect(d).toContainText('Create a user first');
});
